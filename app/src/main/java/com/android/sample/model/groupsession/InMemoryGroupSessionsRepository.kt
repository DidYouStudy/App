  private val writeMutex = Mutex()

  /** Observes public sessions that have not ended yet, in start/end/ID order. */
  override fun observeSessions(endingAfter: Instant): Flow<Result<List<GroupSession>>> =
      sessions
          .map { stored ->
            stored.values
                .filter { it.endsAt.isAfter(endingAfter) }
                .sortedWith(compareBy<GroupSession>({ it.startsAt }, { it.endsAt }, { it.id }))
          }
          .distinctUntilChanged()
          .map { Result.success(it) }

  /** Creates a nonblank identifier unique among identifiers generated by this repository. */
  override fun newSessionId(): String = UUID.randomUUID().toString()

  /** Reads a session by ID, failing with INVALID_ARGUMENT or NOT_FOUND as applicable. */
  override suspend fun getSession(sessionId: String): Result<GroupSession> {
    if (sessionId.isBlank()) return invalidArgument()
    val session =
        sessions.value[sessionId] ?: return Result.failure(EventsException(EventsError.NOT_FOUND))
    return Result.success(session)
  }

  /**
   * Creates a creator-owned session or updates one without changing its stored membership or
   * creation time.
   *
   * Invalid arguments fail with INVALID_ARGUMENT; unauthorized writes fail with PERMISSION_DENIED.
   */
  override suspend fun saveSession(userId: String, session: GroupSession): Result<Unit> {
    if (userId.isBlank()) return invalidArgument()
    return writeMutex.withLock {
      val existing = sessions.value[session.id]
      if (existing == null) {
        if (userId != session.createdBy) return@withLock permissionDenied()
        sessions.value = sessions.value + (session.id to session)
      } else {
        if (userId != existing.createdBy || session.createdBy != existing.createdBy) {
          return@withLock permissionDenied()
        }
        val updated = session.copy(memberIds = existing.memberIds, createdAt = existing.createdAt)
        sessions.value = sessions.value + (session.id to updated)
      }
      Result.success(Unit)
    }
  }

  /** Deletes a creator-owned session; deleting a missing one succeeds. */
  override suspend fun deleteSession(userId: String, sessionId: String): Result<Unit> {
    if (userId.isBlank() || sessionId.isBlank()) return invalidArgument()
    return writeMutex.withLock {
      val existing = sessions.value[sessionId]
      if (existing != null && userId != existing.createdBy) return@withLock permissionDenied()
      if (existing != null) sessions.value = sessions.value - sessionId
      Result.success(Unit)
    }
  }

  /** Adds a user to membership once, failing for invalid arguments or a missing session. */
  override suspend fun joinSession(userId: String, sessionId: String): Result<Unit> {
    if (userId.isBlank() || sessionId.isBlank()) return invalidArgument()
    return writeMutex.withLock {
      val existing =
          sessions.value[sessionId]
              ?: return@withLock Result.failure(EventsException(EventsError.NOT_FOUND))
      if (userId !in existing.memberIds) {
        sessions.value =
            sessions.value + (sessionId to existing.copy(memberIds = existing.memberIds + userId))
      }
      Result.success(Unit)
    }
  }

  /** Removes a non-creator member; a creator cannot leave and a non-member leave is a no-op. */
  override suspend fun leaveSession(userId: String, sessionId: String): Result<Unit> {
    if (userId.isBlank() || sessionId.isBlank()) return invalidArgument()
    return writeMutex.withLock {
      val existing =
          sessions.value[sessionId]
              ?: return@withLock Result.failure(EventsException(EventsError.NOT_FOUND))
      if (userId == existing.createdBy) return@withLock invalidArgument()
      if (userId in existing.memberIds) {
        sessions.value =
            sessions.value + (sessionId to existing.copy(memberIds = existing.memberIds - userId))
      }
      Result.success(Unit)
    }
  }

  /** Returns INVALID_ARGUMENT for a blank caller-supplied ID. */
  private fun <T> invalidArgument(): Result<T> =
      Result.failure(EventsException(EventsError.INVALID_ARGUMENT))

  /** Returns PERMISSION_DENIED for a write not allowed to the caller. */
  private fun <T> permissionDenied(): Result<T> =
      Result.failure(EventsException(EventsError.PERMISSION_DENIED))
}
